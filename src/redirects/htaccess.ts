import { nap } from '../lib/nap';
import type { Redirect } from './map';

const host = new URL(nap.siteUrl).hostname;
const escapeHost = (value: string): string => value.replace(/\./g, '\\.');

/** Regex for the request path (no leading slash), with and without the trailing slash. */
export function sourcePattern(from: string): string {
  const bare = from.replace(/^\//, '').replace(/\/$/, '');
  const escaped = bare.replace(/[.+?^${}()|[\]\\]/g, '\\$&');
  return from.endsWith('/') ? `^${escaped}/?$` : `^${escaped}$`;
}

export function buildHtaccess(map: readonly Redirect[]): string {
  const lines: string[] = [
    '# Generated by scripts/postbuild.ts from src/redirects/map.ts. Do not edit.',
    'RewriteEngine On',
    '',
    '# HTTP to HTTPS (301)',
    'RewriteCond %{HTTPS} !=on',
    'RewriteCond %{HTTP:X-Forwarded-Proto} !https',
    `RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`,
    '',
    '# www to bare domain (301)',
    `RewriteCond %{HTTP_HOST} ^www\\.${escapeHost(host)}$ [NC]`,
    `RewriteRule ^ https://${host}%{REQUEST_URI} [R=301,L]`,
    '',
    '# Old WordPress URLs (301)',
    ...map.map((entry) => `RewriteRule ${sourcePattern(entry.from)} ${entry.to} [R=301,L]`),
    '',
    'ErrorDocument 404 /404.html',
    '',
    '<IfModule mod_headers.c>',
    '  Header always set X-Content-Type-Options "nosniff"',
    '  Header always set Referrer-Policy "strict-origin-when-cross-origin"',
    '  <If "%{REQUEST_URI} =~ m#^/(_next/static|img)/#">',
    '    Header set Cache-Control "public, max-age=31536000, immutable"',
    '  </If>',
    '</IfModule>',
    '',
  ];
  return lines.join('\n');
}
